/* 库里已有的食材名，优先放行，避免误封（猕猴桃 ≠ 猕猴） */
function isKnownFood(s){
  s = String(s || '').trim();
  if (!s) return false;
  return FOODS.some(f => f.name === s || f.alias.some(a => a === s));
}

function wildlifeMatch(q){
  const s = String(q || '').trim();
  if (!s) return null;
  if (isKnownFood(s)) return null;
  for (const w of WILDLIFE){
    // 只要有一边是单字，就要求完全一致：
    // 避免「蛇果」算蛇、「狗」算狗獾、「翅」算鱼翅
    if (w.length === 1 || s.length === 1){
      if (s === w) return w;
      continue;
    }
    if (s.includes(w) || w.includes(s)) return w;
  }
  return null;
}

