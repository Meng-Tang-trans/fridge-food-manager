function pyOf(s){
  let r = '';
  for (const ch of s){
    if (PINYIN[ch]) r += PINYIN[ch];
    else if (/[a-z0-9]/.test(ch)) r += ch;   // 英文别名原样保留，比如 tortilla
  }
  return r;
}

